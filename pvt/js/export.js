    var i = model.input, c = i.corr;
    var names = {
      dak: 'Dranchuk & Abou-Kassem (1975)', hallYarborough: 'Hall & Yarborough (1973)',
      beggsBrill: 'Beggs & Brill (1973)', sutton: 'Sutton (1985)', standing: 'Standing (1977)',
      wichertAziz: 'Wichert & Aziz (1972)', carr: 'Carr, Kobayashi & Burrows (1954)',
      leeGonzalezEakin: 'Lee, Gonzalez & Eakin (1966)',
      carrKobayashiBurrows: 'Carr, Kobayashi & Burrows (1954)'
    };
    var n = function (k) { return names[k] || k; };

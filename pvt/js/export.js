  function eclipse(model, units) {
    var metric = units === 'metric';
    var i = model.input;
    var cp = function (p) { return metric ? p * K.PSI_BAR : p; };
    var cRs = function (r) { return metric ? r * K.SCFSTB_SM3SM3 : r / 1000; };  /* METRIC sm3/sm3, FIELD Mscf/STB */
    var cBg = function (bg) { return metric ? bg : bg * K.FT3SCF_RBMSCF; };      /* METRIC rm3/sm3, FIELD rb/Mscf  */
    var cRho = function (d) { return metric ? d * K.LBFT3_KGM3 : d; };
    var cComp = function (x) { return metric ? x / K.PSI_BAR : x; };            /* 1/psi -> 1/bar */
    var uP = metric ? 'barsa' : 'psia';
    var uRs = metric ? 'sm3/sm3' : 'Mscf/STB';
    var uBo = metric ? 'rm3/sm3' : 'rb/STB';
    var uBg = metric ? 'rm3/sm3' : 'rb/Mscf';
    var uRho = metric ? 'kg/m3' : 'lb/ft3';
    var uC = metric ? '1/bar' : '1/psi';
    var L = [];

    L.push(stamp(model, '--'));
    L.push('');
    L.push(metric ? 'METRIC' : 'FIELD');
    L.push('');
    L.push('-- Surface densities: oil / water / gas (' + uRho + ')');
    L.push('DENSITY');
    L.push('  ' + col(cRho(model.rhoOsc), 4) + col(cRho(model.rhoWsc), 4) + col(cRho(model.rhoGsc), 6) + ' /');
    L.push('/');
    L.push('');
    L.push('-- Live oil: Rs (' + uRs + ')  Pbub (' + uP + ')  Bo (' + uBo + ')  Visc (cP)');
    L.push('-- Each record: the saturated node first, then its undersaturated branch.');
    L.push('PVTO');
    model.pvto.forEach(function (rec) {
      rec.rows.forEach(function (r, k) {
        var head = k === 0 ? col(cRs(rec.rs), 6, 12) : pad('', 12);
        L.push('  ' + head + col(cp(r.p), 3, 12) + col(r.bo, 5, 12) + col(r.muo, 5, 12) +
          (k === rec.rows.length - 1 ? ' /' : ''));
      });
    });
    L.push('/');
    L.push('');
    L.push('-- Dry gas: P (' + uP + ')  Bg (' + uBg + ')  Visc (cP)');
    L.push('PVDG');
    model.gas.forEach(function (g) {
      L.push('  ' + col(cp(g.p), 3, 12) + col(cBg(g.bg), 6, 14) + col(g.mug, 6, 12));
    });
    L.push('/');
    L.push('');
    var wRef = model.water[Math.floor(model.water.length / 2)];
    var wHi = model.water[model.water.length - 1];
    var visc = (wHi.muw - wRef.muw) / Math.max(wHi.p - wRef.p, 1e-9) / wRef.muw;
    L.push('-- Water: Pref (' + uP + ')  Bw (' + uBo + ')  Cw (' + uC + ')  Visc (cP)  Viscosibility (' + uC + ')');
    L.push('PVTW');
    L.push('  ' + col(cp(wRef.p), 3, 12) + col(wRef.bw, 5, 12) + sci(cComp(wRef.cw), 5, 14) +
      col(wRef.muw, 5, 12) + sci(cComp(visc), 5, 14) + ' /');
    L.push('');
    L.push('-- Rock: Pref (' + uP + ')  Cr (' + uC + ')');
    L.push('ROCK');
    L.push('  ' + col(cp(i.pRefRock), 3, 12) + sci(cComp(i.rockComp), 5, 14) + ' /');
    L.push('');
    return L.join('\n');
  }


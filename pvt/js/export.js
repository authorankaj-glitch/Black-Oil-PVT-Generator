      '  Gas pseudo-criticals       : ' + n(c.pcrit) + ' + ' + n(c.inertCorr),
      '  Gas z-factor               : ' + n(c.z),
      '  Gas viscosity              : ' + n(c.mug),
      '  Water properties           : McCain (1991) / Osif (1988)'
